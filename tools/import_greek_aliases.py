"""One-off: write aliases/gr.toml from the app's bundled manifest and the
relation ids its Overpass client holds, so that Greek region ids, names and
the hand-checked neighbours carry over unchanged.

    HAPPYROADS_APP=D:/_Programming/_Projects/HappyRoads python tools/import_greek_aliases.py

It has run once and is kept as the record of where aliases/gr.toml came from.
The two files it reads were removed from the app once the published files
replaced them, so to run it again, point HAPPYROADS_APP at a checkout of the
app at commit f196ee1 or earlier. aliases/gr.toml is now edited by hand.
"""

import json
import os
import re
from pathlib import Path

APP = Path(os.environ['HAPPYROADS_APP'])
OUT = Path(__file__).resolve().parent.parent / 'aliases' / 'gr.toml'


def _s(value):
    # A JSON string is a valid TOML basic string, escapes included.
    return json.dumps(value, ensure_ascii=False)


def _table(names):
    return '{ ' + ', '.join(f'{k} = {_s(v)}' for k, v in sorted(names.items())) + ' }'


def main():
    dart = (APP / 'lib/core/data/overpass_http_client.dart').read_text(encoding='utf-8')
    single = dict(re.findall(r"'([a-z-]+)': (\d+),", dart.split('_regionRelationIds')[1].split('};')[0]))
    city_block = dart.split('_cityRelationIds')[1].split('};')[0]
    cities = {k: re.findall(r'\d+', v) for k, v in re.findall(r"'([a-z-]+)': \[([^\]]*)\]", city_block)}

    manifest = json.loads((APP / 'assets/data/region_data/manifest.json').read_text(encoding='utf-8'))
    country = manifest['countries'][0]

    lines = ['# Generated by tools/import_greek_aliases.py from the app as it shipped',
             '# before this generator existed. Keeps every Greek id a device may hold.',
             '', '[country]', f'name = {_s("Ελλάδα")}', f'names = {{ el = {_s("Ελλάδα")}, en = "Greece" }}', '']
    for region in country['regions']:
        if region.get('parts'):
            lines += ['[whole]', f'id = {_s(region["id"])}', f'name = {_s(region["name"])}',
                      f'names = {_table(region.get("names", {}))}', '']
            continue
        rid = region['id']
        relations = cities.get(rid) or [single[rid]]
        lines += ['[[region]]', f'id = {_s(rid)}',
                  f'relations = [{", ".join(relations)}]',
                  f'name = {_s(region["name"])}',
                  f'names = {_table(region.get("names", {}))}',
                  f'neighbours = [{", ".join(_s(n) for n in region["neighborIds"])}]', '']

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
